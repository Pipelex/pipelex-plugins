    @pytest.mark.parametrize("target_name", ["prod", "codex", "mistral-vibe"])
    def test_orphans_on_a_successful_write_continue_the_run(self, target_name: str) -> None:
        """Ruled by the founder on 2026-09-13, against the review's recommendation: a non-empty
        `orphans[]` on a successful write does **not** end the run. The skill goes on to write the
        sidecar, add the dependencies and write the call site, and reports the orphan paths loudly
        on the way — and because the hazardous cause (another method's same-named files already
        overwritten by the write that just succeeded) is indistinguishable from the benign ones
        inside the tool, that report is the only protection the user gets — in refresh mode too, where the
        ruling's own continuation is what puts a sidecar on a directory another method's tree may still
        occupy, so a later refresh overwrites those same-named files again.

        Three regions have to agree, so all three are checked: the step-6 branch, its row in the
        failure table, and the refresh-mode path. The biting assertion is the halt-vocabulary scan
        over each of them rather than a search for one phrase — whoever later "fixes" the asymmetry
        with the neighbouring branch will write *some* instruction to end the run, and the struck
        "do nothing else" is in the same closed set, which is what makes its replacement rather
        than its clarification enforced. The neighbour is pinned in the opposite direction, so
        neither half of the deliberate asymmetry can be flattened without a test going red.
        """
        body = self.render(target_name)
        orphans = self.the_line(body, "- Success with **`orphans[]` non-empty**")
        disowned = self.the_line(body, "- Success with **`is_current: false`**")
        row = self.the_line(body, "| success with `orphans[]` non-empty |")
        # Refresh mode's orphans rule is one sentence run of a long paragraph, so cut it out rather
        # than scanning the paragraph — the rest of it is about hashes and the call site.
        opens, closes = "**A non-empty `orphans[]` does not end a refresh either**", "there as here."
        paragraph = self.the_line(body, opens)
        refresh = paragraph[paragraph.index(opens) : paragraph.index(closes, paragraph.index(opens)) + len(closes)]

        for where, line in (("step 6", orphans), ("the failure table", row), ("refresh mode", refresh)):
            found = self.HALT_VOCABULARY.search(line)
            assert found is None, f"{target_name}: {where}'s orphans path ends the run ({found.group(0)!r} in {line!r})"

        # The run continues, and the steps it continues into are named.
        assert "**Carry on to step 7 and report loudly.**" in orphans
        assert "finish the integration — the sidecar, the dependencies, the call site" in orphans
        assert "**continue to step 7**" in row
        assert "the refresh runs on through the type checker, the call site and the sidecar" in refresh

        # The report is the protection, so it owes the paths, the overwrite possibility and the remedy.
        assert "The report names the orphan paths" in orphans
        assert "may therefore have been overwritten by the write that just succeeded" in orphans
        assert "a dedicated directory per generation as the fix" in orphans
        assert "this write may have overwritten same-named files of another method" in row
        assert "the regeneration has overwritten the other method's same-named files again" in refresh
        assert "rather than describing the orphans as merely stale" in refresh
        assert "`orphans_truncated: true` → say orphan detection was partial" in orphans
        assert "`orphans_truncated: true` → say detection was partial" in row
        assert "`orphans_truncated: true` → say detection was partial" in refresh

        # An orphan is never deleted — the ruling changed whether to proceed, nothing else.
        assert "never delete an orphan" in orphans
        assert "never delete" in row
        assert "never deletes them" in refresh

        # The asymmetry with the neighbour is stated, and the neighbour still ends the run.
        assert "**The branch below ends the run and this one does not, and the asymmetry is deliberate**" in orphans
        assert "Unlike the row below, this one does not end the run" in row
        assert "An `is_current: false` still ends the refresh, there as here." in refresh
        assert "and stop; never commit a tree the check rejects" in disowned

        # Step 4 enumerates the stops that leave a lock with no sidecar; orphans is no longer one.
        assert "every stop between them — a reported `is_current: false`, a partial write whose retry also failed —" in body

    def test_the_call_sites_submit_the_whole_bundle_not_just_main(self) -> None:
        """Generation takes every `.mthds` file of the bundle, so the run must too.

        A call site that submits `main.mthds` alone type-checks, passes the offline gate, and then
        fails at load time on exactly the multi-file methods codegen handled correctly.
        """
        typescript = (self.REFERENCES_DIR / "typescript.md").read_text(encoding="utf-8")
        assert "mthds_contents: await readBundle()," in typescript
        # An interface has no implicit index signature, so it is not assignable to Record<string, unknown>.
        assert "export type SummarizePdfInputs = {" in typescript
        assert "export interface SummarizePdfInputs" not in typescript
        assert "**`SummarizePdfInputs` is a `type`, not an `interface`, and that is load-bearing.**" in typescript
        # A script merely named `codegen` is not evidence of a Pipelex harness.
        assert "read the script before believing it" in typescript
        assert 'name.endsWith(".mthds")' in typescript
        assert "mthds_contents: [bundle]" not in typescript
        # Its own relative imports need extensions on the resolution that meets the emitter defect.
        assert "**The three relative imports above are extensionless, which is correct only on a bundler resolution.**" in typescript

        python = (self.REFERENCES_DIR / "python.md").read_text(encoding="utf-8")
        assert "mthds_contents=_read_bundle()," in python
        assert 'sorted(BUNDLE_DIR.rglob("*.mthds"))' in python
        assert "BUNDLE_PATH" not in python

    def test_the_gate_fails_closed_on_a_malformed_sources_and_does_not_truncate(self) -> None:
        """The offline gate is the one executable artifact here, so two properties are pinned.

        A sidecar whose `sources` is present but not an object must fail the way an unreadable one
        does: coerced to `{}` it would check nothing, print nothing and exit 0 — the single input
        that is both silent and green. And the verdict's explanation must survive a pipe, which
        `process.exit` does not guarantee.
        """
        gate = (self.REFERENCES_DIR / "codegen-check.mjs").read_text(encoding="utf-8")
        # Neither `??` nor `?.` on the way to `sources`: both turn a hostile value into the
        # legitimate absent case. `?.` is the subtler of the two — a sidecar whose whole content is
        # `null`, `[]`, `"x"` or `42` is valid JSON and not an object, and `sidecar?.sources` makes
        # every one of them `undefined`, so the gate claims "a by-ref or by-id integration" and
        # exits 0 over a file that says nothing of the kind. Guard the sidecar, then its `sources`.
        assert "const sources = sidecar.sources;" in gate
        assert "const sources = sidecar?.sources" not in gate
        assert "?? {}" not in gate
        assert 'if (typeof sidecar !== "object" || sidecar === null || Array.isArray(sidecar)) {' in gate
        assert "not a JSON object, so staleness cannot be ruled out" in gate
        assert 'if (typeof sources !== "object" || sources === null || Array.isArray(sources)) {' in gate
        assert "is not an object, so staleness cannot be ruled out" in gate
        # No branch is both silent and green: absent and empty both announce themselves.
        assert "records no sources — a by-ref or by-id integration; source staleness does not apply" in gate
        assert "process.exitCode = await main(process.argv);" in gate
        # The default decoder strips a BOM, which would hash a BOM'd artifact as current.
        assert 'new TextDecoder("utf-8", { fatal: true, ignoreBOM: true })' in gate
        assert "process.exit(await main" not in gate

    @pytest.mark.parametrize(
        ("sidecar", "expected_exit"),
        [
            ("null", 1),
            ("[]", 1),
            ('"a string"', 1),
            ("42", 1),
            ("true", 1),
            ('{"method": {"id": "mt_x"}}', 0),
            ('{"sources": {}}', 0),
            ('{"sources": null}', 1),
            ('{"sources": []}', 1),
        ],
    )
    def test_the_gate_runs_and_refuses_a_non_object_sidecar(self, sidecar: str, expected_exit: int, tmp_path: Path) -> None:
        """Run the gate, do not read it. Every case here was found by executing it, and the
        non-object-sidecar ones reported `current` with exit 0 before the guard went in — the
        failure the file's own header calls its one job to avoid.

        The lock check is made to yield no verdict (no `codegen.lock`), which the script reports on
        its own and which suppresses the sidecar check — so the cases are driven through a tree that
        reaches `checkSources`, i.e. one with a lock. Skipped when no `node` is on the PATH.
        """
        node = shutil.which("node")
        if node is None:
            pytest.skip("no node on the PATH")
        gate = tmp_path / "codegen-check.mjs"
        gate.write_bytes((self.REFERENCES_DIR / "codegen-check.mjs").read_bytes())
        # A lock the SDK cannot even be asked about would short-circuit the sidecar check, so stub
        # the one import and let the tree report itself current.
        stub = tmp_path / "node_modules" / "@pipelex" / "sdk"
        stub.mkdir(parents=True)
        (stub / "package.json").write_text(
            '{"name":"@pipelex/sdk","version":"0.0.0-stub","type":"module","main":"index.js","exports":{".":"./index.js"}}',
            encoding="utf-8",
        )
        (stub / "index.js").write_text(
            "export class CodegenLockError extends Error {}\n"
            "export const isStampableArtifactPath = (p) => p.endsWith('.ts') || p.endsWith('.py');\n"
            "export const runCodegenCheck = async () => ({ isCurrent: true, drifts: [], "
            "crateFingerprint: 'stubfingerprint', engineVersion: '0.0.0' });\n",
            encoding="utf-8",
        )
        tree = tmp_path / "generated" / "m"
        tree.mkdir(parents=True)
        (tree / "codegen.lock").write_text("lock_version = 1\n", encoding="utf-8")
        (tree / "types.ts").write_text("export const x = 1;\n", encoding="utf-8")
        (tree / "sources.json").write_text(sidecar, encoding="utf-8")
        result = subprocess.run(
            [node, str(gate), "generated/m"],
            cwd=tmp_path,
            capture_output=True,
            text=True,
            check=False,
        )
        assert result.returncode == expected_exit, (
            f"sidecar {sidecar!r}: expected exit {expected_exit}, got {result.returncode}\nstdout: {result.stdout}\nstderr: {result.stderr}"
        )
        if expected_exit == 0:
            assert "codegen-check: current" in result.stdout
        else:
            assert "codegen-check: drift" in result.stdout

