"""Pin the load-bearing rules of the pipelex-integrate skill template and its references."""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from scripts.gen_skill_docs import load_target_config, render_templates, resolve_output_dir, setup_static_assets


class TestPipelexIntegrateSkill:
    """The skill is executable guidance, so these tests guard the rules a user's
    codebase depends on: the write arm is the only arm, generated bytes are never
    touched, one directory per method, orphans are never deleted, sources are never
    mixed, a project-owned harness is kept, and the signature comes from the verdict.
    """

    REPO_ROOT = Path(__file__).parents[2]
    TEMPLATE = REPO_ROOT / "templates" / "skills" / "pipelex-integrate" / "SKILL.md.j2"
    REFERENCES_DIR = REPO_ROOT / "skills" / "pipelex-integrate" / "references"
    REFERENCES = ("typescript.md", "python.md", "codegen-check.mjs")
    RULES = (
        "**The write arm, always.** Every `mthds_codegen` call passes `output_dir`.",
        "never by calling again without `output_dir` and writing the returned bytes yourself",
        "**Generated files are never opened for editing, never formatted, never linted.**",
        "**One directory per method.**",
        "You never delete an orphan either",
        "**Never generate from one source and run from another.**",
        "**A project that owns a codegen harness keeps it.** Never write a second generated layout",
        "**No `dropWireNulls` / `wireOutput` helper.**",
        "Do this **before** step 6",
    )

    @property
    def integrate(self) -> str:
        return self.TEMPLATE.read_text(encoding="utf-8")

    def test_the_rules_that_never_bend_are_stated(self) -> None:
        body = self.integrate
        for rule in self.RULES:
            assert rule in body, f"missing rule: {rule}"

    def test_signature_comes_from_the_verdict_and_the_heuristic_is_absent(self) -> None:
        body = self.integrate
        assert "A valid verdict carries **`main_pipe`**" in body
        assert "**`explicit: true`** — the one call in this plugin that wants the ceremonial" in body
        # The by-elimination output-concept heuristic was designed, then made obsolete before it shipped.
        assert "candidate output concepts" not in body
        assert "minus the input concepts minus natives" not in body
        # A by-ref / by-id source with no signature stops instead of guessing.
        assert "STOP and say the verdict carries no signature to type this integration exactly" in body
        # The entry pipe is the verdict's, which follows a package manifest; its absence has three causes, not one.
        assert "`main_pipe.pipe_ref` is the pipe a run with no pipe selector executes" in body
        assert "the method settles **no entry pipe**" in body
        assert "the workshop **predates the signature**" in body

    def test_the_wire_null_helper_is_never_installed(self) -> None:
        body = self.integrate
        assert "wire-output.ts" not in body
        assert "wireOutput(results" not in body
        for reference in self.REFERENCES:
            assert "dropWireNulls" not in (self.REFERENCES_DIR / reference).read_text(encoding="utf-8")

    def test_failure_posture_pins_the_403_and_the_orphans(self) -> None:
        body = self.integrate
        assert "a **403** on `mthds_codegen` is a feature gate, not a key problem" in body
        assert 'never say "check your key" for a 403' in body
        assert '`kind: "paywall"`' in body
        assert "report by name, never delete" in body
        assert "never delete, move or clear the named file" in body
        assert "and never offer to" in body
        # A lock is not this method's without a sidecar naming it: same file names mean a silent overwrite, not an orphan.
        assert "is this method's only when a `sources.json` beside it names this method" in body
        assert "would silently overwrite the other method's stamped files rather than report an orphan" in body
        assert "report `drifts[]` verbatim and stop" in body
        # The emitter's extensionless import is a known defect: named, never patched in the stamped tree.
        assert 'a known defect of the ts-zod emitter, which writes `from "./types"`' in body
        assert "Changing the project's `moduleResolution` is the user's call to make, not yours" in body

    def test_method_id_warns_and_refresh_leaves_the_call_site_alone(self) -> None:
        body = self.integrate
        assert "The catalog is unversioned" in body
        assert "proceed only on the user's say-so" in body
        assert "**The call site is edited only if it no longer type-checks or the `pipe` record no longer matches the signature**" in body
        assert '"generator": "pipelex-integrate"' in body

    def test_python_gate_asymmetry_is_honest(self) -> None:
        body = self.integrate
        assert "**Python, `python-pydantic`**: **no gate is installed.**" in body
        assert "do not add `pipelex` as a dependency to get a gate" in body
        assert "pipelex codegen check <dir>" in body
        python = (self.REFERENCES_DIR / "python.md").read_text(encoding="utf-8")
        assert "**no gate is installed.**" in python
        assert "there is **no barrel** in `pipelex_sdk` by design" in python

    def test_the_check_script_imports_only_node_builtins_and_the_sdk(self) -> None:
        script = (self.REFERENCES_DIR / "codegen-check.mjs").read_text(encoding="utf-8")
        imports = re.findall(r'^import .* from "([^"]+)";$', script, flags=re.MULTILINE)
        assert imports, "the script should import through static ESM imports"
        for module in imports:
            assert module.startswith("node:") or module == "@pipelex/sdk", f"unexpected import: {module}"
        assert "runCodegenCheck" in script and "isStampableArtifactPath" in script
        assert "process.stdout.write" in script and "process.stderr.write" in script
        assert "console." not in script

    @pytest.mark.parametrize("target_name", ["prod", "codex", "mistral-vibe"])
    def test_every_platform_renders_the_skill_and_its_references(self, target_name: str) -> None:
        config = load_target_config(self.REPO_ROOT / "targets", target_name)
        rendered = render_templates(
            self.REPO_ROOT / "templates",
            self.REPO_ROOT,
            config.template_vars,
            include_skills=["pipelex-integrate"],
            target_name=config.name,
        )
        body = next(content for path, content in rendered.items() if path.match("skills/pipelex-integrate/SKILL.md"))
        assert "# Integrate an MTHDS method into a codebase" in body
        assert "{%" not in body
        assert "{{" not in body
        for rule in self.RULES:
            assert rule in body, f"{target_name}: missing rule: {rule}"
        if target_name == "prod":
            assert "mcp__plugin_pipelex_pipelex__mthds_codegen" in body
            assert "offer `/pipelex-scaffold`" in body
        else:
            assert "mcp__" not in body
            assert "open `../pipelex-scaffold/SKILL.md`" in body

        references_dir = resolve_output_dir(self.REPO_ROOT, config.source) / "skills" / "pipelex-integrate" / "references"
        for reference in self.REFERENCES:
            assert (references_dir / reference).is_file(), f"{target_name}: missing references/{reference}"

    @pytest.mark.parametrize("target_name", ["prod", "codex", "mistral-vibe"])
    def test_the_build_copies_the_references_byte_for_byte(self, target_name: str, tmp_path: Path) -> None:
        """The check script is executable know-how: a stale or re-encoded copy is a broken gate."""
        config = load_target_config(self.REPO_ROOT / "targets", target_name)
        setup_static_assets(self.REPO_ROOT, tmp_path, self.REPO_ROOT / "templates", config.include_skills)
        produced = tmp_path / "skills" / "pipelex-integrate" / "references"
        for reference in self.REFERENCES:
            assert (produced / reference).is_file(), f"{target_name}: the build did not copy references/{reference}"
            assert (produced / reference).read_bytes() == (self.REFERENCES_DIR / reference).read_bytes()
