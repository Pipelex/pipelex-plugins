    def orphans_branch(self, body: str) -> str:
        """Step 6's orphans branch: the one place the skill states the condition the run continues on."""
        return self.the_line(body, "- **`orphans[]` non-empty and `drifts[]` empty**")

    @pytest.mark.parametrize("target_name", ["prod", "codex", "mistral-vibe"])
    def test_the_run_continues_on_orphans_alone_and_on_nothing_else(self, target_name: str) -> None:
        """Re-ruled by the founder on 2026-09-13 (`L-260912-3d5693`), replacing an earlier ruling of
        the same day that a review proved unimplementable. **The run continues when `orphans[]` is
        non-empty and `drifts[]` is empty, read off those two fields and never inferred from
        `is_current`; anything that also drifted ends the run.**

        What this test guards is the *condition*, because the condition is the whole decision and its
        absence is what made the first implementation green and wrong. `pipelex-mcp` sets
        `is_current: false` the moment a directory holds an orphan, so there is no
        success-with-orphans verdict to branch on: a branch phrased on the verdict is unreachable,
        and a branch phrased on nothing is a blanket exemption that swallows real drift. So the region
        that tells the agent to carry on must name both halves of the condition and must say the
        verdict is not what distinguishes them, and the stopping row must claim every other false
        verdict.

        The size diet stated the condition once, at step 6, where it used to sit in step 6, the
        failure table and refresh mode in three wordings. Refresh mode now branches as step 6 does
        and the stop table names step 6's case, so a fourth wording coming back fails here.
        """
        body = self.render(target_name)
        region = self.orphans_branch(body)
        assert self.CONTINUE_VOCABULARY.search(region), f"{target_name}: step 6's orphans branch no longer tells the agent to proceed"
        assert self.ORPHANS_NON_EMPTY.search(region), f"{target_name}: the branch continues without requiring a non-empty `orphans[]`"
        assert self.DRIFTS_EMPTY.search(region), f"{target_name}: the branch continues without requiring an empty `drifts[]`: {region!r}"
        assert self.CONDITION.search(region), f"{target_name}: the branch names both halves but states neither as its condition: {region!r}"
        assert self.ABSENT_DRIFTS_IS_EMPTY.search(region), (
            f"{target_name}: the branch sends the agent to read `drifts[]` without saying it is present only when non-empty: {region!r}"
        )
        assert self.NOT_THE_VERDICT.search(region), (
            f"{target_name}: the branch does not say it is read off the two lists and never from `is_current`: {region!r}"
        )
        halt = self.HALT_VOCABULARY.search(region)
        assert halt is None, f"{target_name}: step 6's orphans branch ends the run ({halt.group(0)!r} in {region!r})"
        assert len(self.CONDITION.findall(body)) == 1, f"{target_name}: the continuing condition is stated more than once"

        # Refresh mode branches as step 6 does and restates nothing of the condition.
        refresh = self.reference("refresh.md", target_name)
        assert "Its result is branched exactly as step 6 branches it" in refresh
        assert "the orphans case carries on here as it does there, on the same condition" in refresh
        assert "every other non-current result ends the refresh" in refresh
        assert self.CONDITION.search(refresh) is None, f"{target_name}: refresh mode restates the condition instead of naming step 6's"

        # The stopping row claims every false verdict the condition above does not, so the two are
